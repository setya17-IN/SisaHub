export const featuredMaterials = materials.slice(0, 6);
export const favoriteMaterials = materials.filter((material) => material.isFavorite);

export function getMaterialById(id: string) {
  return materials.find((material) => material.id === id);
}

export function getOwnerById(id: string) {
  return Object.values(owners).find((owner) => owner.id === id);
}

export function toMaterialCardItem(material: Material): MaterialCardItem {
  return {
    id: material.id,
    title: material.title,
    category: material.category,
    quantityLabel: `${material.quantity} ${material.unit}`,
    conditionLabel: MATERIAL_CONDITION_LABELS[material.condition],
    conditionTone: material.condition === "new" ? "primary" : material.condition === "good" ? "info" : "accent",
    free: material.priceType === "free",
    priceAmount: material.priceAmount,
    city: material.city,
    distance: material.distanceKm ? `${material.distanceKm} km` : null,
    ownerName: material.owner.name,
    ownerAvatar: material.owner.avatar,
    imageUrl: material.imageUrl,
    isFavorite: material.isFavorite,
  };
}

export const materialCategories = (Object.keys(MATERIAL_CATEGORY_LABELS) as Array<Material["category"]>).map((category) => ({
  category,
  label: MATERIAL_CATEGORY_LABELS[category],
  count: materials.filter((material) => material.category === category).length,
}));
